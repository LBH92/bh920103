export class MarketCalendarService {
  private events: CalendarEvent[] = MASTER_CALENDAR_EVENTS;

  /**
   * Get all events with optional filters (year, month, market, type, symbol)
   */
  public getEvents(options: {
    year?: number;
    month?: number;
    market?: CalendarMarket;
    type?: CalendarEventType;
    symbol?: string;
  } = {}): { events: CalendarEvent[]; total: number; source: string; fetchedAt: string } {
    let filtered = [...this.events];

    if (options.year && options.month) {
      const ymPrefix = `${options.year}-${String(options.month).padStart(2, '0')}`;
      filtered = filtered.filter(e => e.date.startsWith(ymPrefix));
    } else if (options.year) {
      const yPrefix = `${options.year}-`;
      filtered = filtered.filter(e => e.date.startsWith(yPrefix));
    }

    if (options.market && options.market !== 'ALL') {
      filtered = filtered.filter(e => e.market === options.market || e.market === 'GLOBAL');
    }

    if (options.type) {
      filtered = filtered.filter(e => e.type === options.type);
    }

    if (options.symbol) {
      const sym = options.symbol.toUpperCase();
      filtered = filtered.filter(e => e.symbol?.toUpperCase() === sym);
    }

    // Sort chronologically by startDateTime
    filtered.sort((a, b) => new Date(a.startDateTime).getTime() - new Date(b.startDateTime).getTime());

    return {
      events: filtered,
      total: filtered.length,
      source: '한국거래소(KRX) · U.S. NYSE/NASDAQ · 한국은행 · 미국 연준 공식 캘린더',
      fetchedAt: new Date().toISOString(),
    };
  }

  /**
   * Get calendar summary (today's events, this week's events, upcoming high impact)
   */
  public getSummary(baseDate: Date = new Date()): CalendarSummary {
    const todayStr = baseDate.toISOString().slice(0, 10);
    const nowMs = baseDate.getTime();
    const oneWeekMs = nowMs + 7 * 24 * 60 * 60 * 1000;
    const currentMonthPrefix = `${baseDate.getFullYear()}-${String(baseDate.getMonth() + 1).padStart(2, '0')}`;

    const todayEvents = this.events.filter(e => e.date === todayStr);

    const weekEvents = this.events.filter(e => {
      const eTime = new Date(e.startDateTime).getTime();
      return eTime >= nowMs - (24 * 3600 * 1000) && eTime <= oneWeekMs;
    }).sort((a, b) => new Date(a.startDateTime).getTime() - new Date(b.startDateTime).getTime());

    const upcomingHighImpact = this.events.filter(e => {
      const eTime = new Date(e.startDateTime).getTime();
      return eTime >= nowMs && e.importance === 'HIGH';
    }).slice(0, 5);

    const thisMonthEvents = this.events.filter(e => e.date.startsWith(currentMonthPrefix));

    return {
      todayEvents,
      weekEvents,
      upcomingHighImpact,
      counts: {
        totalThisMonth: thisMonthEvents.length,
        holidays: thisMonthEvents.filter(e => e.type === 'HOLIDAY').length,
        economic: thisMonthEvents.filter(e => e.type === 'ECONOMIC').length,
        earnings: thisMonthEvents.filter(e => e.type === 'EARNINGS').length,
        dividends: thisMonthEvents.filter(e => e.type === 'DIVIDEND').length,
      },
      serverTime: new Date().toISOString(),
    };
  }

  /**
   * Get single event by ID
   */
  public getEventById(id: string): CalendarEvent | undefined {
    return this.events.find(e => e.id === id);
  }
}

export const marketCalendarService = new MarketCalendarService();
